export function getRecipeById(id: string): Recipe | undefined {
  return recipes.find((r) => r.id === id);
}

export function getRecipesByTier(tier: 1 | 2 | 3): Recipe[] {
  return recipes.filter((r) => r.tier === tier);
}

export function getRecipeTooltip(recipe: Recipe): string {
  const lines = [
    recipe.printTitle,
    `Cost: ${recipe.printCostText}`,
    recipe.printEffectText,
  ];

  if (recipe.requiresTags.length > 0) {
    lines.push(`Requires: ${recipe.requiresTags.join(', ')}`);
  }
  if (recipe.requiresBuilds.length > 0) {
    lines.push(`Requires builds: ${recipe.requiresBuilds.join(', ')}`);
  }
  if (recipe.maintenance) {
    const upkeep = Object.entries(recipe.maintenance.cost)
      .map(([mat, qty]) => `${qty} ${mat}`)
      .join(' + ');
    lines.push(`Upkeep: ${upkeep}${recipe.maintenance.startRound ? ` starting R${recipe.maintenance.startRound}` : ''}${recipe.maintenance.interval ? ` every ${recipe.maintenance.interval} rounds` : ''}`);
  }
  if (recipe.designNotes) {
    lines.push(recipe.designNotes);
  }

  return lines.join('\n');
}
